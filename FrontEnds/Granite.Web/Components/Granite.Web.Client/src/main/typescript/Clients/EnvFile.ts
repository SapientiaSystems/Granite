export function toEnvFile(clientId: string,secret: string): string
{
    return "GRANITE_CLIENT_ID=" + clientId + "\nGRANITE_CLIENT_SECRET=" + secret + "\n";
}

export function envFileName(name: string): string
{
    return name.replace(/[^A-Za-z0-9._-]/g,"_") + ".env";
}

