package granite.outbox.server.shared;

public
class TestHelper
{
    public static void
    sleepForSeconds(int seconds)
    {
        try
        {
            Thread.sleep(seconds * 1000);
        }
        catch (InterruptedException e)
        {
            Thread.currentThread().interrupt();
        }
    }
}

